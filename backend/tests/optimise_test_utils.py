"""Test utility helpers for generating explicit synthetic operational evidence.

All evidence generated by this module is strictly for automated unit and integration
testing, representing explicit synthetic test assumptions.
"""

from decimal import Decimal
from typing import Optional, Set

from app.optimise.evidence import (
    CustomerAuthorizationEvidence,
    ManagerFreightApprovalEvidence,
    TaskExecutionProgressEvidence,
    TechnicianFairnessEvidence,
    VehiclePhysicalEvidence,
    WorkshopEvidenceBundle,
)
from app.schemas.domain import DealershipSnapshotSchema, TaskStatus, VehiclePhysicalState


def make_synthetic_evidence(
    snapshot: DealershipSnapshotSchema,
    authorize_all: bool = True,
    authorized_ro_ids: Optional[Set[str]] = None,
    with_progress: bool = True,
    with_vehicle_evidence: bool = True,
    with_fairness: bool = True,
    current_tick: int = 96,
) -> WorkshopEvidenceBundle:
    """Constructs an explicit synthetic WorkshopEvidenceBundle for test scenarios."""
    customer_auths = {}
    target_ros = {r.ro_id for r in snapshot.repair_orders} if authorize_all else (authorized_ro_ids or set())
    for r in snapshot.repair_orders:
        is_auth = r.ro_id in target_ros
        customer_auths[r.ro_id] = CustomerAuthorizationEvidence(
            ro_id=r.ro_id,
            is_authorized=is_auth,
            authorized_amount_usd=Decimal("500.00") if is_auth else None,
        )

    freight_approvals = {}
    for o in snapshot.supplier_offers:
        freight_approvals[o.offer_id] = ManagerFreightApprovalEvidence(
            offer_id=o.offer_id,
            is_approved=True,
            approved_amount_usd=o.freight_surcharge_usd,
            approved_by="TEST_MANAGER",
        )

    progress_evidence = {}
    if with_progress:
        for t in snapshot.tasks:
            # Set explicit remaining duration equal to estimated duration for incomplete tasks
            rem = t.estimated_duration_ticks if t.status != TaskStatus.COMPLETED else 0
            progress_evidence[t.task_id] = TaskExecutionProgressEvidence(
                task_id=t.task_id,
                status=t.status,
                current_tick=current_tick,
                remaining_duration_ticks=rem,
            )

    vehicle_evidence = {}
    if with_vehicle_evidence:
        for r in snapshot.repair_orders:
            # In S-MATH-01, RO-104 is immobilized in BAY-01; others are in holding or bays
            is_imm = (
                r.physical_state == VehiclePhysicalState.IMMOBILIZED_ON_LIFT
                or (hasattr(r.physical_state, "value") and r.physical_state.value == "IMMOBILIZED_ON_LIFT")
            )
            vehicle_evidence[r.vehicle_id] = VehiclePhysicalEvidence(
                vehicle_id=r.vehicle_id,
                ro_id=r.ro_id,
                physical_state=r.physical_state,
                current_bay_id=r.assigned_bay_id if is_imm else None,
                is_in_holding=not is_imm,
                vehicle_weight_lbs=getattr(r, "vehicle_weight_lbs", 3800),
                fitment_verified=True,
            )

    fairness_evidence = {}
    if with_fairness:
        for tech in snapshot.technicians:
            fairness_evidence[tech.tech_id] = TechnicianFairnessEvidence(
                tech_id=tech.tech_id,
                skill_group="GENERAL_MECHANICAL",
                historical_allocated_hours=Decimal("40.0"),
                median_peer_hours=Decimal("40.0"),
            )

    return WorkshopEvidenceBundle(
        current_tick=current_tick,
        customer_authorizations=customer_auths,
        manager_freight_approvals=freight_approvals,
        task_progress=progress_evidence,
        vehicle_evidence=vehicle_evidence,
        technician_fairness=fairness_evidence,
        available_porter_tech_ids={t.tech_id for t in snapshot.technicians},
    )
